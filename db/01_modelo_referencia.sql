-- ---------------------------------------------------------------------
-- 1. Catálogos (sin claves foráneas)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS rol (
    id_rol       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30)  NOT NULL,          -- ADMINISTRADOR | VENDEDOR | CLIENTE (la API los muestra como "Administrador"...)
    descripcion  VARCHAR(150),
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS region (
    id_region  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(60) NOT NULL,
    CONSTRAINT uk_region_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS estado_pedido (
    id_estado  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(30) NOT NULL,              -- En preparación | Enviado | Entregado | Cancelado
    CONSTRAINT uk_estado_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS tipo_entrega (
    id_tipo_entrega  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(60) NOT NULL,
    CONSTRAINT uk_tipo_entrega_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS metodo_pago (
    id_metodo_pago  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(60) NOT NULL,
    CONSTRAINT uk_metodo_pago_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS marca (
    id_marca  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(60) NOT NULL,
    CONSTRAINT uk_marca_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60)  NOT NULL,
    slug          VARCHAR(60)  NOT NULL,          -- generado desde el nombre: "Baterías y Percusión" -> baterias-y-percusion
    imagen        VARCHAR(255) NOT NULL,          -- si no se envía, el backend usa /img/logotipo.jpg
    CONSTRAINT uk_categoria_nombre UNIQUE (nombre),
    CONSTRAINT uk_categoria_slug   UNIQUE (slug)
);


-- ---------------------------------------------------------------------
-- 2. Ubicación: región -> comuna
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS comuna (
    id_comuna  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(60) NOT NULL,
    id_region  INT         NOT NULL,
    CONSTRAINT uk_comuna_region UNIQUE (nombre, id_region),
    CONSTRAINT fk_comuna_region FOREIGN KEY (id_region) REFERENCES region (id_region)
);


-- ---------------------------------------------------------------------
-- 3. Usuarios y sus direcciones
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,          -- nombre completo, como en el registro del frontend
    correo         VARCHAR(120) NOT NULL,          -- se guarda en minúsculas
    password_hash  VARCHAR(100) NOT NULL,          -- hash BCrypt (costo 12), nunca la contraseña
    activo         BOOLEAN      NOT NULL,          -- "eliminar" = desactivar
    fecha_ingreso  TIMESTAMP(6) NOT NULL,
    id_rol         BIGINT       NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT fk_usuario_rol    FOREIGN KEY (id_rol) REFERENCES rol (id_rol)
);

CREATE TABLE IF NOT EXISTS direccion (
    id_direccion   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calle          VARCHAR(100) NOT NULL,
    numero         VARCHAR(10)  NOT NULL,
    depto          VARCHAR(20),
    codigo_postal  VARCHAR(10),
    id_comuna      INT          NOT NULL,
    id_usuario     BIGINT       NOT NULL,
    CONSTRAINT fk_direccion_comuna  FOREIGN KEY (id_comuna)  REFERENCES comuna (id_comuna),
    CONSTRAINT fk_direccion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);


-- ---------------------------------------------------------------------
-- 4. Catálogo de productos
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS producto (
    id_producto   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(20)  NOT NULL,           -- código visible (GA001), el mismo de la URL /producto/GA001
    nombre        VARCHAR(120) NOT NULL,
    modelo        VARCHAR(60),
    descripcion   VARCHAR(500),
    precio        INT          NOT NULL,           -- pesos chilenos, sin decimales (el backend valida > 0)
    stock         INT          NOT NULL,           -- el backend valida >= 0 y lo descuenta al comprar
    imagen        VARCHAR(255),
    es_oferta     BOOLEAN      NOT NULL,
    activo        BOOLEAN      NOT NULL,           -- "eliminar" = desactivar (sigue en pedidos antiguos)
    version       BIGINT,                          -- bloqueo optimista: evita que dos ventas pisen el mismo stock
    id_categoria  BIGINT       NOT NULL,
    id_marca      BIGINT       NOT NULL,
    CONSTRAINT uk_producto_codigo    UNIQUE (codigo),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria),
    CONSTRAINT fk_producto_marca     FOREIGN KEY (id_marca)     REFERENCES marca (id_marca)
);


-- ---------------------------------------------------------------------
-- 5. Pedidos y su detalle
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS pedido (
    id_pedido        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(20),                  -- código visible PED-1001 (= 1000 + id_pedido)
    fecha            DATE         NOT NULL,
    cliente_nombre   VARCHAR(100) NOT NULL,        -- copia del nombre al momento de la compra
    cliente_correo   VARCHAR(120) NOT NULL,        -- copia del correo al momento de la compra
    telefono         VARCHAR(20)  NOT NULL,        -- teléfono de contacto de esa compra (lo pide el checkout)
    total            INT          NOT NULL,        -- lo calcula el servidor, nunca el frontend
    id_usuario       BIGINT       NOT NULL,
    id_estado        INT          NOT NULL,
    id_tipo_entrega  INT          NOT NULL,
    id_metodo_pago   INT          NOT NULL,
    id_direccion     BIGINT,                       -- vacío en "Retiro en Tienda"
    CONSTRAINT uk_pedido_codigo       UNIQUE (codigo),
    CONSTRAINT fk_pedido_usuario      FOREIGN KEY (id_usuario)      REFERENCES usuario (id_usuario),
    CONSTRAINT fk_pedido_estado       FOREIGN KEY (id_estado)       REFERENCES estado_pedido (id_estado),
    CONSTRAINT fk_pedido_tipo_entrega FOREIGN KEY (id_tipo_entrega) REFERENCES tipo_entrega (id_tipo_entrega),
    CONSTRAINT fk_pedido_metodo_pago  FOREIGN KEY (id_metodo_pago)  REFERENCES metodo_pago (id_metodo_pago),
    CONSTRAINT fk_pedido_direccion    FOREIGN KEY (id_direccion)    REFERENCES direccion (id_direccion)
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id_detalle       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido        BIGINT       NOT NULL,
    id_producto      BIGINT       NOT NULL,
    codigo           VARCHAR(20)  NOT NULL,        -- copia del código del producto al comprar
    nombre           VARCHAR(120) NOT NULL,        -- copia del nombre del producto al comprar
    precio_unitario  INT          NOT NULL,        -- precio al momento de la compra
    cantidad         INT          NOT NULL,
    subtotal         INT          NOT NULL,        -- cantidad x precio_unitario
    CONSTRAINT fk_detalle_pedido   FOREIGN KEY (id_pedido)   REFERENCES pedido (id_pedido),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto)
);


