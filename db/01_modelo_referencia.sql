-- =====================================================================
-- Sonido Vivo - Modelo de datos (REFERENCIA, PostgreSQL), adaptado al frontend SonidoVivo-main
-- Las tablas las crea Hibernate automáticamente al iniciar el backend
-- (spring.jpa.hibernate.ddl-auto=update) a partir de las clases del paquete model.
-- Este archivo muestra el resultado equivalente en SQL para explicar el modelo.
-- Si prefieren crearlas a mano:  psql -h ENDPOINT_DEL_RDS -U postgres -d sonido_vivo -f db/02_modelo_referencia.sql
--
-- Correspondencia con el frontend (src/data):
--   usuarios.js   -> rol + usuario         (rol: Administrador | Vendedor | Cliente)
--   categorias.js -> categoria             ({ nombre, imagen })
--   productos.js  -> producto              (codigo, nombre, marca, modelo, categoria, stock, precio, imagen, descripcion, esOferta)
--   pedidos.js    -> pedido + detalle_pedido
-- =====================================================================

CREATE TABLE IF NOT EXISTS rol (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30)  NOT NULL,                 -- ADMINISTRADOR | VENDEDOR | CLIENTE (la API los muestra como "Administrador"...)
    descripcion  VARCHAR(150),
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(100) NOT NULL,
    correo            VARCHAR(120) NOT NULL,
    password_hash     VARCHAR(100) NOT NULL,            -- hash BCrypt, nunca la contraseña
    direccion         VARCHAR(200),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE, -- eliminar = desactivar
    rol_id            BIGINT       NOT NULL,
    fecha_creacion    TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol (id)
);

CREATE TABLE IF NOT EXISTS categoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(60)  NOT NULL,
    imagen  VARCHAR(255) NOT NULL,                      -- ej. /img/acustica.png
    CONSTRAINT uk_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS producto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(20)  NOT NULL,                -- ej. GA001 (2 letras + 3 números)
    nombre        VARCHAR(120) NOT NULL,
    marca         VARCHAR(60)  NOT NULL,                -- texto, como en el frontend
    modelo        VARCHAR(60),                          -- ej. F310
    descripcion   VARCHAR(500),
    precio        INTEGER      NOT NULL,                -- CLP; la API exige > 0
    stock         INTEGER      NOT NULL,                -- la API exige >= 0
    imagen        VARCHAR(255),
    es_oferta     BOOLEAN      NOT NULL DEFAULT FALSE,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,   -- eliminar = ocultar del catálogo
    categoria_id  BIGINT       NOT NULL,
    version       BIGINT,                               -- control de concurrencia
    CONSTRAINT uk_producto_codigo UNIQUE (codigo),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
);

CREATE TABLE IF NOT EXISTS pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(20),                        -- PED-1001 (1000 + id)
    fecha           DATE         NOT NULL,
    usuario_id      BIGINT       NOT NULL,
    cliente_nombre  VARCHAR(100) NOT NULL,
    cliente_correo  VARCHAR(120) NOT NULL,
    telefono        VARCHAR(20)  NOT NULL,
    direccion       VARCHAR(200) NOT NULL,
    tipo_entrega    VARCHAR(60)  NOT NULL,              -- Retiro en Tienda (Viña del Mar) | Despacho Starken | Despacho Chilexpress
    metodo_pago     VARCHAR(40)  NOT NULL,              -- Tarjeta de crédito | Tarjeta de débito | Transferencia bancaria (pago simulado)
    estado          VARCHAR(20)  NOT NULL,              -- EN_PREPARACION | ENVIADO | ENTREGADO | CANCELADO
    total           INTEGER      NOT NULL,              -- lo calcula el servidor
    CONSTRAINT uk_pedido_codigo UNIQUE (codigo),
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT       NOT NULL,
    producto_id      BIGINT       NOT NULL,
    codigo           VARCHAR(20)  NOT NULL,             -- copia del código al comprar
    nombre           VARCHAR(120) NOT NULL,             -- copia del nombre al comprar
    cantidad         INTEGER      NOT NULL,             -- 1..99 y nunca mayor al stock (409)
    precio_unitario  INTEGER      NOT NULL,             -- precio congelado al momento de comprar
    subtotal         INTEGER      NOT NULL,
    CONSTRAINT fk_detalle_pedido   FOREIGN KEY (pedido_id)   REFERENCES pedido (id),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);
